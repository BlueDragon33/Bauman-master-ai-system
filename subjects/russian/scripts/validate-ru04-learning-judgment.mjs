import fs from 'node:fs';
import assert from 'node:assert/strict';
const j=p=>JSON.parse(fs.readFileSync(p,'utf8'));
const contract=j('subjects/russian/docs/ru04/RUSSIAN_RU04_LEARNING_JUDGMENT_CONTRACT.json');
const evidence=j('subjects/russian/docs/ru04/RUSSIAN_RU04_EVIDENCE_INTERFACE.json');
const planner=j('subjects/russian/docs/ru04/RUSSIAN_RU04_PLANNER_SUPPORT_POLICY.json');
const attempts=j('subjects/russian/docs/p4/RUSSIAN_ATTEMPT_STATE_SCHEMA.json');
const mastery=j('subjects/russian/docs/p4/RUSSIAN_MASTERY_STATE_SCHEMA.json');
const srs=j('subjects/russian/docs/p4/RUSSIAN_SRS_STATE_SCHEMA.json');
assert.equal(contract.authorities.mastery,'subjects/russian/assets/assessment-mastery.js');
assert.equal(contract.authorities.reviewOrchestration,'subjects/russian/assets/adaptive-planner.js');
assert(attempts.invariants.some(x=>/first submitted attempt never overwritten/i.test(x)));
assert(mastery.rules.some(x=>/activity\/completion is not mastery/i.test(x)));
assert.equal(srs.activePassive.reference,'no compulsory SRS unless activated');
for(const s of ['listening','speaking','writing','technical','research']) assert(planner.skillStarvationProtection.includes(s));
for(const x of ['audio-playback','watch-time','page-open','AI-duration','ASR-similarity-alone']) assert(evidence.nonAuthoritativeSignals.includes(x));
assert(planner.forbiddenRecomputeTriggers.includes('render'));
assert.equal(planner.intensiveModeRule.includes('never rewrite mastery'),true);
console.log(JSON.stringify({ok:true,masteryOwner:contract.authorities.mastery,plannerOwner:contract.authorities.reviewOrchestration,evidenceTypes:evidence.authoritativeEvidenceTypes.length}));
