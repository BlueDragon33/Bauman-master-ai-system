import fs from 'node:fs';
import assert from 'node:assert/strict';
const j=p=>JSON.parse(fs.readFileSync(p,'utf8'));
const tech=j('subjects/russian/data/technical-concepts.json');
const af=j('subjects/russian/data/academic-functions.json');
const rd=j('subjects/russian/data/reading.json');
const pt=j('subjects/russian/data/performance-tasks.json');
const arch=j('subjects/russian/docs/ru06/RUSSIAN_RU06_PRODUCTION_ARCHITECTURE.json');
const lineage=j('subjects/russian/docs/ru06/RUSSIAN_RU06_SOURCE_CLAIM_LINEAGE_CONTRACT.json');
const rep=j('subjects/russian/docs/ru06/RUSSIAN_RU06_REPRESENTATION_INTEGRITY_POLICY.json');
const map=j('subjects/russian/docs/ru06/RUSSIAN_RU06_PERFORMANCE_MAP.json');
assert((tech.concepts||[]).length>=60,'technical concept coverage regressed');
assert((af.functions||[]).length>=15,'academic function coverage regressed');
assert((rd.tasks||[]).length>=12,'reading progression regressed');
assert((pt.tasks||[]).length>=10,'performance task coverage regressed');
for(const x of ['numbers','equations','code-identifiers','experimental-results']) assert(rep.protected.includes(x));
for(const x of ['source-fact','interpretation','learner-claim','generated-suggestion']) assert(lineage.claimTypes.includes(x));
for(const x of ['presentation','defense','novel-technical-transfer']) assert(arch.progression.includes(x));
assert.deepEqual(map.stages.flatMap(x=>x.targets),Array.from({length:16},(_,i)=>'R'+String(i+11).padStart(2,'0')));
console.log(JSON.stringify({ok:true,technicalConcepts:tech.concepts.length,academicFunctions:af.functions.length,readingTasks:rd.tasks.length,performanceTasks:pt.tasks.length}));

const index=fs.readFileSync('subjects/russian/index.html','utf8');
const runtime=fs.readFileSync('subjects/russian/assets/academic-production-runtime.js','utf8');
assert.match(index,/assets\/academic-production-runtime\.js/,'RU06 production runtime is not loaded');
assert.match(runtime,/PRACTICE_ONLY/,'RU06 production draft must remain practice-only');
assert.match(runtime,/writesMastery:false/,'RU06 production runtime must not write mastery');
assert.ok(fs.existsSync('tests/russian-ru06-production-browser.mjs'),'RU06 browser evidence missing');
