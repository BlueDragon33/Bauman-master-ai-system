import fs from 'node:fs';
import vm from 'node:vm';
import assert from 'node:assert/strict';
const window={};
const context={window,Date,Math,Object,Array,Number,String};
vm.createContext(context);
vm.runInContext(fs.readFileSync('subjects/russian/assets/review-scheduler.js','utf8'),context,{filename:'review-scheduler.js'});
const s=window.RussianReviewScheduler;
assert.ok(s);
assert.equal(s.schema,'RUSSIAN_REVIEW_SCHEDULER_V1');
const base=Date.parse('2026-10-01T00:00:00.000Z');
const forgot=s.schedule({kind:'vocabulary-active',result:'forgot',successStreak:4,lapses:2,nowMs:base});
assert.equal(forgot.gapDays,0); assert.equal(forgot.nextSuccessStreak,0); assert.equal(forgot.nextLapses,3);
const unsure=s.schedule({kind:'vocabulary-active',result:'unsure',successStreak:4,lapses:2,nowMs:base,gaps:[1,3,7,14]});
assert.equal(unsure.gapDays,1); assert.equal(unsure.nextSuccessStreak,0);
const recall1=s.schedule({kind:'vocabulary-active',result:'recalled',successStreak:0,lapses:0,nowMs:base,gaps:[1,3,7,14]});
const recall2=s.schedule({kind:'vocabulary-active',result:'recalled',successStreak:1,lapses:0,nowMs:base,gaps:[1,3,7,14]});
assert.equal(recall1.gapDays,1); assert.equal(recall2.gapDays,3);
const passive=s.schedule({kind:'vocabulary-passive',result:'recalled',successStreak:0,lapses:0,nowMs:base});
assert.ok(passive.gapDays>=recall1.gapDays);
const integrated=s.schedule({kind:'integrated-performance',result:'recalled',successStreak:0,lapses:0,nowMs:base});
assert.equal(integrated.gapDays,2);
const again=s.schedule({kind:'integrated-performance',result:'recalled',successStreak:0,lapses:0,nowMs:base});
assert.deepEqual(integrated,again,'scheduler must be deterministic for same inputs');
console.log('Russian RU04 review scheduler runtime: PASS');
