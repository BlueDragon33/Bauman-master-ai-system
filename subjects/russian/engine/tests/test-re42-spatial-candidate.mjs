import assert from 'node:assert/strict';
import fs from 'node:fs';
import {evaluateSpatialCandidateAction,validateSpatialCandidate} from '../world/spatial-candidate-runtime.mjs';
const read=url=>JSON.parse(fs.readFileSync(url,'utf8'));
const draft=read(new URL('../content/fixtures/real-life-spatial.r2-ai-proposal.json',import.meta.url));
const source=read(new URL('../content/fixtures/real-life-scenes.v1.json',import.meta.url));
const report=validateSpatialCandidate(draft);
assert.equal(report.ok,true,report.errors.join('; '));
assert.equal(report.sceneCount,15);
assert.equal(report.worldCount,5);
assert.equal(report.canonicalPublicationReady,false);
assert.deepEqual(draft.scenes.map(s=>s.sceneId),source.scenes.map(s=>s.sceneId));
assert.equal(draft.scenes.every(s=>s.humanApproval===false),true);
assert.equal(draft.scenes.filter(s=>s.expectedAction.kind==='point-to-location').length,11);
assert.equal(draft.scenes.filter(s=>s.expectedAction.kind==='handover-object').length,3);
assert.equal(draft.scenes.filter(s=>s.expectedAction.kind==='dialogue-intent').length,1);
const scene=id=>draft.scenes.find(x=>x.sceneId===id);
const world=id=>draft.worlds.find(x=>x.worldId===id);
const type=(w,id)=>w.nodes.find(n=>n.nodeId===id)?.visualType;
assert.equal(type(world('dorm'),'room-12'),'numbered-room');
assert.equal(type(world('university'),'auditorium-12'),'lecture-room');
assert.equal(type(world('dorm'),'shower-room'),'shower-room');
assert.equal(type(world('metro'),'metro-route-map'),'map-board');
assert.equal(type(world('metro'),'station-entrance'),'stairs');
assert.equal(scene('rl-08-metro').expectedAction.targetId,'metro-route-map');
assert.equal(scene('rl-11-dorm').expectedAction.targetId,'room-12');
assert.equal(scene('rl-13-university').expectedAction.targetId,'auditorium-12');
assert.ok(!scene('rl-05-shop').russianDraft.includes('Дай воду'));
for(const item of draft.scenes){
  const action=item.expectedAction;
  const success=evaluateSpatialCandidateAction({scene:item,...action});
  assert.equal(success.success,true);
  assert.equal(success.masteryMutation,false);
  assert.equal(success.linguisticAuthority,false);
  assert.equal(success.canonicalPublicationReady,false);
  const failure=evaluateSpatialCandidateAction({scene:item,kind:'point-to-location',targetId:'wrong'});
  assert.equal(failure.success,false);
}
