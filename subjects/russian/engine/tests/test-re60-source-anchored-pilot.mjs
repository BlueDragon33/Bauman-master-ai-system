import assert from 'node:assert/strict';
import {loadRu03SourceAnchoredPilot,validateRu03SourceAnchoredPilot,buildRu03SourceAnchoredPilot} from '../knowledge/ru03-reference-library.mjs';
import {buildRe49ReviewInventory} from '../review/re49-review-packets-r4.mjs';
import {buildExternalReviewHandoff} from '../review/re50-external-review-handoff.mjs';
const inventory=buildRe49ReviewInventory();
const item=inventory.items.find(x=>x.itemId==='spatial:rl-05-shop:instruction');
const pilot=loadRu03SourceAnchoredPilot();
assert.equal(validateRu03SourceAnchoredPilot(pilot,item).ok,true);
const v=buildRu03SourceAnchoredPilot(item,{pilot});
assert.equal(v.status,'AI_EVIDENCE_CANDIDATE');
assert.equal(v.lexicalClaims.find(x=>x.surface==='воды').stressMarked,'воды́');
assert.equal(v.audioStatus,'NOT_AUDITED');
const handoff=buildExternalReviewHandoff({inventory});
assert.equal(handoff.entries.find(x=>x.itemId===item.itemId).sourceAnchoredPilot.lexicalClaims.length,4);
assert.equal(handoff.entries.filter(x=>x.sourceAnchoredPilot!==null).length,1);
assert.equal(handoff.canonicalPublicationReady,false);
const stale=structuredClone(pilot);stale.textRu='Можно воду?';
assert.equal(validateRu03SourceAnchoredPilot(stale,item).ok,false);
const forgery=structuredClone(pilot);forgery.textAuthority='HUMAN_RU03';
assert.equal(validateRu03SourceAnchoredPilot(forgery,item).ok,false);
const wrong=structuredClone(pilot);wrong.claims[2].stressMarked='во́ды';
assert.equal(validateRu03SourceAnchoredPilot(wrong,item).ok,false,'lexical surface mismatch blocked; plural vowel stress confusion');
const untrusted=structuredClone(pilot);untrusted.claims[1].sourceUrl='https://example.org';
assert.equal(validateRu03SourceAnchoredPilot(untrusted,item).ok,false);
console.log(JSON.stringify({ok:true,suite:'RE60_RU03_GROUNDED_STRESS_PILOT',pilotItems:1,reviewItems:43,rawAudioApproval:false}));
