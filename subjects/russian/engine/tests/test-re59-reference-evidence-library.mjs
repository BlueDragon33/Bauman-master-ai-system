import assert from 'node:assert/strict';
import {loadRu03ReferenceLibrary, validateRu03ReferenceLibrary, buildRu03ReferenceGuide} from '../knowledge/ru03-reference-library.mjs';
import {buildExternalReviewHandoff} from '../review/re50-external-review-handoff.mjs';

const library = loadRu03ReferenceLibrary();
assert.equal(validateRu03ReferenceLibrary(library).ok,true);
const guide = buildRu03ReferenceGuide({library});
assert.equal(guide.sources.length,4);
assert.equal(guide.authority,'NONE');
assert.equal(guide.canonicalPublicationReady,false);
assert.equal(guide.sources.every(s=>s.evidenceStatus==='DISCOVERY_POINTER_ONLY'),true);
assert.equal(guide.sources.every(s=>s.redistribution==='PROHIBITED'),true);
assert.equal(guide.sources.find(s=>s.sourceId==='commonvoice-ru27').uses.includes('WORD_STRESS'),false,'ASR speech must not masquerade as normative stress');
const fake = structuredClone(library);
fake.humanApproval = true;
assert.equal(validateRu03ReferenceLibrary(fake).ok,false,'unverified auto approval must fail');
const badLicense = structuredClone(library);
badLicense.sources[0].redistribution = 'ALLOWED';
assert.equal(validateRu03ReferenceLibrary(badLicense).ok,false,'copyright bypass must fail');
const badKind = structuredClone(library);
badKind.sources[3].uses = ['WORD_STRESS'];
assert.equal(validateRu03ReferenceLibrary(badKind).ok,false,'ASR cannot certify literary stress');
const badUrl = structuredClone(library);
badUrl.sources[0].url = 'http://example.com';
assert.equal(validateRu03ReferenceLibrary(badUrl).ok,false,'unsafe URL must fail');
const dup = structuredClone(library);
dup.sources[1].sourceId = dup.sources[0].sourceId;
assert.equal(validateRu03ReferenceLibrary(dup).ok,false,'duplicate source must fail');
const handoff = buildExternalReviewHandoff();
assert.equal(handoff.referenceGuide.sources.length,4);
assert.equal(handoff.referenceGuide.authority,'NONE');
assert.equal(handoff.itemCount,43);
assert.equal(handoff.audioReady,false);
assert.equal(handoff.canonicalPublicationReady,false);
console.log(JSON.stringify({ok:true,suite:'RE59_RU03_REFERENCE_EVIDENCE_LIBRARY',sources:4,handoffItems:43,authority:'NONE',negativeCases:5}));
