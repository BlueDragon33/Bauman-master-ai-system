import assert from 'node:assert/strict';
import fs from 'node:fs';
import {buildR2HumanReviewQueue,verifyR2HumanReviewQueue} from '../review/r2-candidate-human-review-queue.mjs';
import {validateHumanReviewDecision} from '../review/review-decision-registry.mjs';
import {evaluateHumanReviewGate} from '../authoring/canonical-scene-compiler.mjs';
const read=url=>JSON.parse(fs.readFileSync(url,'utf8'));
const spatial=read(new URL('../content/fixtures/real-life-spatial.r2-ai-proposal.json',import.meta.url));
const dialogues=read(new URL('../content/fixtures/repair-dialogues.r1-ai-proposal.json',import.meta.url));
const queue=buildR2HumanReviewQueue(spatial,dialogues);
assert.equal(verifyR2HumanReviewQueue(queue),true);
assert.equal(queue.total,19);
assert.equal(queue.spatialScenes,15);
assert.equal(queue.dialogueScenes,4);
assert.equal(queue.autoApproved,0);
assert.equal(queue.canonicalPublicationReady,false);
assert.equal(queue.packets.every(p=>p.reviewDecision===null),true);
assert.equal(queue.packets.every(p=>p.fingerprint.startsWith('fnv1a32-')),true);
const humanGate=evaluateHumanReviewGate({packets:queue.packets,decisions:[]});
assert.equal(humanGate.pending.length,19);
assert.equal(humanGate.approved.length,0);
assert.equal(humanGate.canonicalPublicationReady,false);
const forged={decisionId:'FAKE-AI',sceneId:queue.packets[0].sceneId,revision:queue.packets[0].revision,
fingerprint:queue.packets[0].fingerprint,authority:'RU03',reviewerType:'AI',reviewerId:'automatic',
decision:'APPROVE',decidedAt:'2026-10-08T00:00:00Z'};
assert.equal(validateHumanReviewDecision(forged).ok,false,'AI must not impersonate a RU03 human reviewer');
const stale=structuredClone(spatial);
stale.scenes[10].russianDraft+='!';
const updated=buildR2HumanReviewQueue(stale,dialogues);
assert.notEqual(updated.packets[10].fingerprint,queue.packets[10].fingerprint,'changed exact Russian must invalidate review fingerprint');
assert.equal(updated.packets[9].fingerprint,queue.packets[9].fingerprint,'unrelated unchanged scene should remain stable');
const moved=structuredClone(spatial);
moved.worlds.find(w=>w.worldId==='dorm').nodes.find(n=>n.nodeId==='room-12').x=79;
const reordered=buildR2HumanReviewQueue(moved,dialogues);
assert.notEqual(reordered.packets[10].fingerprint,queue.packets[10].fingerprint,'moved world target must invalidate RU03 review snapshot');
const repairEdited=structuredClone(dialogues);
repairEdited.repair.repeat='Повторите ещё раз, пожалуйста.';
const changedRepair=buildR2HumanReviewQueue(spatial,repairEdited);
assert.notEqual(changedRepair.packets[15].fingerprint,queue.packets[15].fingerprint,'shared repair wording should invalidate dialogue packet');
const bad=structuredClone(queue);
bad.packets[0].reviewDecision=forged;
assert.equal(verifyR2HumanReviewQueue(bad),false,'materialized review queue may not contain fake approvals');
const old=read(new URL('../content/fixtures/real-life-scenes.v1.json',import.meta.url));
assert.equal(old.scenes.length,15);
assert.equal(old.scenes.every(s=>s.status==='FIXTURE_NONCANONICAL_PENDING_RU03'),true);
console.log(JSON.stringify({ok:true,reviewPackets:19,spatial:15,dialogues:4,humanReviewRequired:true,autoApproved:0,sourceImmutable:true,staleFingerprintsBlocked:true}));
