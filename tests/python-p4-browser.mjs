import assert from 'node:assert/strict';
import fs from 'node:fs';
assert.ok(fs.existsSync('subjects/programming/python-lab.html'), 'Programming lab missing');
const {chromium}=await import(process.env.BAUMAN_PLAYWRIGHT_MODULE || 'playwright');
const browser=await chromium.launch({headless:true,...(process.env.BAUMAN_CHROME_PATH?{executablePath:process.env.BAUMAN_CHROME_PATH}:{})});
const base=process.env.BAUMAN_E2E_BASE_URL || 'http://127.0.0.1:3005/';
const errors=[];
try {
  for(const viewport of [{width:1440,height:900},{width:390,height:844}]) {
    const context=await browser.newContext({viewport});
    const page=await context.newPage();
    page.on('pageerror',e=>errors.push(e.message));
    await page.goto(base+'subjects/programming/python-lab.html');
    await page.evaluate(()=>localStorage.setItem('bauman_programming_roadmap_v1_same_ui','{"sentinel":"preserved"}'));
    await page.locator('#pythonCode').fill('print(6 * 7)');
    await page.locator('#pythonRun').click();
    await page.waitForSelector('#pythonStatus[data-status="completed"]');
    assert.match(await page.locator('#pythonOutput').textContent(), /42/);
    await page.locator('#pythonMode').selectOption('test');
    await page.locator('#pythonCode').fill('def solve(values):\n    return sum(values)');
    await page.locator('#pythonRun').click();
    await page.waitForSelector('#pythonStatus[data-status="completed"]');
    assert.match(await page.locator('#pythonTests').textContent(), /4.*0/);
    await page.locator('#pythonMode').selectOption('trace');
    await page.locator('#pythonCode').fill('print(missing_name)');
    await page.locator('#pythonRun').click();
    await page.waitForSelector('#pythonStatus[data-status="runtime_error"]');
    assert.match(await page.locator('#pythonException').textContent(), /NameError/);
    await page.locator('#pythonHint').click();
    assert.match(await page.locator('#pythonAdvice').textContent(), /tên biến/);
    await page.locator('#pythonMode').selectOption('notebook');
    await page.locator('#pythonCode').fill('x = 21\n# %%\nprint(x * 2)');
    await page.locator('#pythonRun').click();
    await page.waitForSelector('#pythonStatus[data-status="completed"]');
    assert.match(await page.locator('#pythonOutput').textContent(), /42/);
    await page.locator('#pythonRestart').click();
    await page.locator('#pythonCode').fill('print(x)');
    await page.locator('#pythonRun').click();
    await page.waitForSelector('#pythonStatus[data-status="runtime_error"]');
    assert.match(await page.locator('#pythonException').textContent(), /NameError/);
    await page.locator('#pythonCode').fill('while True: pass');
    await page.locator('#pythonRun').click();
    await page.locator('#pythonCancel').click();
    assert.equal(await page.locator('#pythonStatus').getAttribute('data-status'),'cancelled');
    await page.waitForTimeout(3500);
    assert.equal(await page.locator('#pythonStatus').getAttribute('data-status'),'cancelled');
    await context.setOffline(true);
    await page.locator('#pythonCode').fill('print(1)');
    await page.locator('#pythonRun').click();
    await page.waitForSelector('#pythonStatus[data-status="provider_unavailable"]');
    await context.setOffline(false);
    await page.reload();
    assert.equal(await page.evaluate(()=>localStorage.getItem('bauman_programming_roadmap_v1_same_ui')),'{"sentinel":"preserved"}');
    assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),true);
    assert.equal(await page.locator('#pythonCode').getAttribute('aria-label'),'Mã Python không tin cậy');
    assert.equal(await page.locator('#pythonStatus').getAttribute('role'),'status');
    await context.close();
  }
  assert.deepEqual(errors,[]);
  console.log(JSON.stringify({status:'PASS',journeys:['desktop','mobile','run','public-tests','trace-error','local-hint','notebook-replay','restart','cancel-stale','offline-unavailable','reload-state'],base}));
} finally {await browser.close();}
