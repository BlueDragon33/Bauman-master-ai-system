import assert from 'node:assert/strict';
import fs from 'node:fs';
import vm from 'node:vm';
const read=p=>fs.readFileSync(p,'utf8');
const main=read('assets/js/main.js'),ref=read('assets/js/subjects-reference-v1.js');
const window={};vm.runInNewContext(read('assets/js/data.js'),{window});
const sandbox={window,DATA:window.BAUMAN_DATA,FINAL_TARGET_QUESTIONS:100,DEFAULT_TARGET_SCORE:80};
vm.createContext(sandbox);
vm.runInContext(main.slice(main.indexOf('function defaultState(){'),main.indexOf('function readState(){')),sandbox);
const normalized=vm.runInContext(`normalizeState({subjects:{math:{priority:'q2',mainPath:'custom/math.html',editorPath:'custom/editor.html'}},lastStudy:{subjectId:'math',path:'custom/math.html'},progress:{math:0}})`,sandbox);
assert.equal(normalized.subjects.math.priority,'q2');assert.equal(normalized.progress.math,0);
assert.ok(!JSON.stringify(normalized).includes('mainPath'),'Application launch configuration must not survive learner normalization');
assert.ok(!JSON.stringify(normalized).includes('editorPath'),'Application editor configuration must not survive learner normalization');
assert.equal(normalized.lastStudy.path,undefined,'Last study stores learner subject choice, not launch transport');
assert.doesNotMatch(main,/\.mainPath|\.editorPath/,'Presentation must not read/write raw compatibility fields');
assert.doesNotMatch(read('assets/js/planning-main.js'),/\.mainPath|\.editorPath/,'Mission owner must delegate launch transport to the adapter');
assert.doesNotMatch(ref,/openSubjectEditor|openEditor|Dữ liệu môn/,'Reference learner UI must not expose an editor');
const detailStart=main.indexOf('  subjectDetailHTML(s){');
assert.ok(detailStart>0);
const detail=main.slice(detailStart,main.indexOf('\n  courseHTML(',detailStart));
assert.doesNotMatch(detail,/openSubjectEditor|Dữ liệu môn/,'Canonical learner UI must not expose an editor');
const html=read('index.html');
for(const name of ['hub-subject-config.js','hub-subject-launch.js'])assert.ok(html.indexOf(name)>0&&html.indexOf(name)<html.indexOf('assets/js/main.js'),'Integration boundary must load before main');
console.log('HUB_SUBJECT_INTEGRATION_STATIC_PASS');
