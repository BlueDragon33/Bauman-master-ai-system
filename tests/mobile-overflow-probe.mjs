import { chromium } from 'playwright';
const BASE=process.env.BAUMAN_E2E_BASE_URL||'http://127.0.0.1:4173/';
const browser=await chromium.launch({headless:true});
const ctx=await browser.newContext({viewport:{width:1440,height:1000}});
const page=await ctx.newPage();
const deviceId='a'.repeat(64),deviceCode='BM-PROBE-001';
await page.route('http://127.0.0.1:3003/**',async route=>{
 const req=route.request(),u=new URL(req.url());
 const cors={'access-control-allow-origin':'*','access-control-allow-methods':'GET,POST,OPTIONS','access-control-allow-headers':'content-type,authorization','cache-control':'no-store'};
 if(req.method()==='OPTIONS')return route.fulfill({status:204,headers:cors,body:''});
 const headers={...cors,'content-type':'application/json'},send=body=>route.fulfill({status:200,headers,body:JSON.stringify(body)});
 if(u.pathname==='/api/device/register'||u.pathname==='/api/device/status')return send({device:{deviceId,deviceCode,status:'approved'}});
 if(u.pathname==='/api/device/challenge')return send({challengeId:'c',signingInput:`probe:${deviceId}`});
 if(u.pathname==='/api/device/verify')return send({sessionToken:'bm1.probe',expiresAt:Date.now()+3600000,device:{deviceId,deviceCode,status:'approved'}});
 if(u.pathname==='/api/device/heartbeat')return send({device:{deviceId,deviceCode,status:'approved'}});
 return route.fulfill({status:404,headers,body:'{}'});
});
await page.goto(BASE,{waitUntil:'domcontentloaded'});
await page.waitForFunction(()=>document.documentElement.dataset.baumanDeviceAccess==='authorized',{timeout:15000});
await page.locator('#loginEmail').fill('probe@example.test');
await page.locator('#loginPass').fill('probe-pass');
await page.locator('#loginBtn').click();
await page.waitForFunction(()=>!document.getElementById('appRoot')?.classList.contains('hidden'));
await page.waitForSelector('.hub2-subjects');
await page.setViewportSize({width:390,height:844});
await page.evaluate(()=>{window.app?.page?.('home',false);window.app?.home?.()});
await page.waitForSelector('.hub2-subjects');
await page.waitForTimeout(80);
const out=await page.evaluate(()=>{
 const home=document.querySelector('#page-home');
 const info=e=>{if(!e)return null;const r=e.getBoundingClientRect(),s=getComputedStyle(e);return{tag:e.tagName,cls:e.className,left:r.left,right:r.right,width:r.width,client:e.clientWidth,scroll:e.scrollWidth,cssWidth:s.width,minWidth:s.minWidth,maxWidth:s.maxWidth,display:s.display,overflowX:s.overflowX,overflowY:s.overflowY,boxSizing:s.boxSizing,justifySelf:s.justifySelf,gridTemplateColumns:s.gridTemplateColumns,position:s.position}};
 const selectors=['.hub2-dashboard','.hub2-layout','.hub2-maincol','.hub2-subjects','.hub2-continue','.hub2-stats','.hub2-bottom','.hub2-rail','.hub2-assistant','.hub2-schedule','.hub2-ach-grid','.hub2-overall','[data-academic2026="home"]','.academic2026-panel'];
 const nodes=Object.fromEntries(selectors.map(sel=>[sel,info(document.querySelector(sel))]));
 const edge=home.getBoundingClientRect().left+home.scrollWidth;
 const nearEdge=[...home.querySelectorAll('*')].map(e=>({e,r:e.getBoundingClientRect()})).filter(x=>x.r.right>=edge-6&&x.r.right<=edge+6).map(x=>info(x.e)).slice(0,30);
 const broad=[...home.querySelectorAll('*')].map(e=>({e,r:e.getBoundingClientRect(),s:getComputedStyle(e)})).filter(x=>x.r.width>home.clientWidth+1||x.r.right>home.getBoundingClientRect().right+1).filter(x=>{let p=x.e.parentElement;while(p&&p!==home){const s=getComputedStyle(p);if(['auto','scroll','hidden','clip'].includes(s.overflowX)&&p.scrollWidth>p.clientWidth)return false;p=p.parentElement}return true}).sort((a,b)=>b.r.right-a.r.right).slice(0,30).map(x=>info(x.e));
 return{innerWidth,bodyMode:document.body.dataset.hubViewport,home:info(home),edge,nodes,nearEdge,broad};
});
console.log('MOBILE_OVERFLOW_PROBE2',JSON.stringify(out));
await browser.close();