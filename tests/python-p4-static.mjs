import assert from 'node:assert/strict';
import fs from 'node:fs';
import vm from 'node:vm';
const evidence='prompts/subjects/python/evidence/';
for(const name of ['PYTHON_EXECUTION_CAPABILITY_CONTRACT.md','PYTHON_SANDBOX_SECURITY_CONTRACT.md','PYTHON_RUNTIME_ENVIRONMENT_POLICY.md','PYTHON_NOTEBOOK_REPRODUCIBILITY_POLICY.md','PYTHON_TEST_DEBUG_PROVIDER_CONTRACT.md','PYTHON_DATA_TOOLING_CONTRACT.md','PYTHON_AI_CODING_TUTOR_CONTRACT.md','PYTHON_RUNTIME_GOLDEN_FIXTURES.json','PYTHON05_INPUT_CONTRACT.md']) assert.ok(fs.existsSync(evidence+name),name);
const manifest=JSON.parse(fs.readFileSync('subjects/programming/subject-manifest.json'));
const sandbox={window:{}};
vm.runInNewContext(fs.readFileSync('subjects/programming/subject-manifest.js','utf8'),sandbox);
assert.deepEqual(JSON.parse(JSON.stringify(sandbox.window.SUBJECT_MANIFEST.pythonRuntime)),manifest.pythonRuntime);
assert.equal(manifest.pythonRuntime.officialAssessment,false);
assert.equal(manifest.pythonRuntime.offlineExecution,false);
assert.equal(manifest.pythonRuntime.learnerExecutionEnabled,false);
assert.equal(manifest.pythonRuntime.availability,'local-companion-only');
const facade=fs.readFileSync('subjects/programming/assets/python-runtime.js','utf8');
const lab=fs.readFileSync('subjects/programming/assets/python-lab.js','utf8');
assert.doesNotMatch(facade+lab,/\beval\s*\(|\bnew\s+Function\s*\(|localStorage\.(setItem|clear|removeItem)|innerHTML\s*=/);
assert.match(lab,/api\.run\(/);
assert.match(facade,/adapter\.pythonRuntime/);
assert.match(lab,/nextResult\.status==='stale_result'/);
assert.match(fs.readFileSync('runtime/python/Dockerfile','utf8'),/FROM python@sha256:[a-f0-9]{64}/);
const ids=JSON.parse(fs.readFileSync(evidence+'PYTHON_RUNTIME_GOLDEN_FIXTURES.json')).fixtures.map(f=>f.id);
for(const id of ['infinite-loop','huge-allocation','output-flood','path-traversal','env-read','network','subprocess','unsafe-pickle','stale-result','hidden-test-leak']) assert.ok(ids.includes(id));
console.log(JSON.stringify({status:'PASS',check:'PYTHON04 integration wiring and required deliverables',securityFixtures:ids.length,officialAssessment:false,offlineExecution:false}));
